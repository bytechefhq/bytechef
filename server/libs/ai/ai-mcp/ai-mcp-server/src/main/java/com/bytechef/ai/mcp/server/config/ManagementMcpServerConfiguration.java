/**
 * Configuration for ByteChef MCP Server using Streamable HTTP transport.
 *
 * This configuration registers a set of deterministic CE automation/platform tools directly, and folds in any
 * {@link McpServerToolCallbackContributor} beans (EE deployments contribute the Copilot subagent agent-tools). The
 *
 * @author Ivica Cardic
 */
@Configuration
@ConditionalOnProperty(name = "bytechef.ai.mcp.server.enabled", havingValue = "true", matchIfMissing = true)
public class ManagementMcpServerConfiguration {

    // Generated by McpInstructionFragmentGenerator (claude-code-plugin:plugin-tools) from the mcp transport
    // fences carried by the plugin skills; regenerate with ./gradlew
    // :claude-code-plugin:plugin-tools:generateMcpInstructions
    // after editing a skill. Never hand-edit this resource.
    private static final String MCP_INSTRUCTIONS_RESOURCE = "bytechef/mcp-instructions.md";

    private static final String ALWAYS_SECTION_HEADING = "## always";

    private static final String TOOLS_SECTION_HEADING_PREFIX = "## tools: ";

    private final ComponentTools componentTools;
    private final ProjectTools projectTools;
    private final ProjectWorkflowTools projectWorkflowTools;
    private final TaskTools taskTools;
    private final TaskDispatcherTools taskDispatcherTools;
    private final ScriptTools scriptTools;
    private final ClusterElementTools clusterElementTools;
    private final List<McpServerToolCallbackContributor> mcpServerToolCallbackContributors;

    @SuppressFBWarnings("EI")
    public ManagementMcpServerConfiguration(
        ComponentTools componentTools, ProjectTools projectTools, ProjectWorkflowTools projectWorkflowTools,
        TaskTools taskTools, TaskDispatcherTools taskDispatcherTools, ScriptTools scriptTools,
        ClusterElementTools clusterElementTools,
        List<McpServerToolCallbackContributor> mcpServerToolCallbackContributors) {

        this.componentTools = componentTools;
        this.projectTools = projectTools;
        this.projectWorkflowTools = projectWorkflowTools;
        this.taskTools = taskTools;
        this.taskDispatcherTools = taskDispatcherTools;
        this.scriptTools = scriptTools;
        this.clusterElementTools = clusterElementTools;
        this.mcpServerToolCallbackContributors = mcpServerToolCallbackContributors;
    }

    @Bean
    WebMvcStreamableServerTransportProvider webMvcStreamableHttpServerTransportProvider() {
        return WebMvcStreamableServerTransportProvider.builder()
            .mcpEndpoint("/api/management/{secretKey}/mcp")
            .build();
    }

    @Bean
    WebMvcStreamableServerTransportProvider canonicalWebMvcStreamableHttpServerTransportProvider() {
        return WebMvcStreamableServerTransportProvider.builder()
            .mcpEndpoint("/api/management/mcp")
            .build();
    }

    @Bean
    RouterFunction<ServerResponse> mcpRouterFunction() {
        return webMvcStreamableHttpServerTransportProvider().getRouterFunction();
    }

    @Bean
    RouterFunction<ServerResponse> canonicalMcpRouterFunction() {
        return canonicalWebMvcStreamableHttpServerTransportProvider().getRouterFunction();
    }

    @Bean
    McpAsyncServer mcpAsyncServer() {
        return createMcpAsyncServer(webMvcStreamableHttpServerTransportProvider());
    }

    @Bean
    McpAsyncServer canonicalMcpAsyncServer() {
        return createMcpAsyncServer(canonicalWebMvcStreamableHttpServerTransportProvider());
    }

    /**
     * Assembles the {@code initialize} result's {@code instructions} field (MCP SDK 2.0's
     * {@code McpServer.AsyncSpecification#instructions}) from the generated fragment resource — the only sequencing
     * guidance external MCP clients (Claude Desktop, Cursor) get, since they never see the Copilot/AI Hub system
     * prompt. The {@code ## always} section is always included. A {@code ## tools: X, Y, Z} section — one fence's body,
     * naming every tool that fence covers — is included when ANY of X, Y, Z is present in {@code registeredToolNames}:
     * tool sets arrive per contributor and are effectively all-or-nothing, so dropping useful sequencing guidance
     * because one of several names is missing would be the worse failure. A fragment naming only renamed or removed
     * tools is silently dropped rather than pointing a client at nothing.
     */
    static String buildInstructions(Set<String> registeredToolNames) {
        List<String> lines = readMcpInstructionFragments().lines()
            .toList();

        StringBuilder instructions = new StringBuilder();
        StringBuilder currentSection = null;
        boolean includeCurrentSection = false;

        for (String line : lines) {
            if (line.equals(ALWAYS_SECTION_HEADING) || line.startsWith(TOOLS_SECTION_HEADING_PREFIX)) {
                if (includeCurrentSection) {
                    appendSection(instructions, currentSection);
                }

                currentSection = new StringBuilder(line);
                includeCurrentSection = line.equals(ALWAYS_SECTION_HEADING)
                    || sectionToolNames(line).stream()
                        .anyMatch(registeredToolNames::contains);

                continue;
            }

            if (currentSection != null) {
                currentSection.append('\n')
                    .append(line);
            }
        }

        if (includeCurrentSection) {
            appendSection(instructions, currentSection);
        }

        return instructions.toString();
    }

    private static List<String> sectionToolNames(String toolsSectionHeading) {
        String namesPart = toolsSectionHeading.substring(TOOLS_SECTION_HEADING_PREFIX.length());

        return Arrays.stream(namesPart.split(","))
            .map(String::strip)
            .toList();
    }

    private static void appendSection(StringBuilder instructions, StringBuilder section) {
        if (!instructions.isEmpty()) {
            instructions.append("\n\n");
        }

        instructions.append(section.toString()
            .strip());
    }

    private static String readMcpInstructionFragments() {
        try (InputStream inputStream = ManagementMcpServerConfiguration.class.getClassLoader()
            .getResourceAsStream(MCP_INSTRUCTIONS_RESOURCE)) {

            if (inputStream == null) {
                throw new IllegalStateException("Missing classpath resource " + MCP_INSTRUCTIONS_RESOURCE);
            }

            return new String(inputStream.readAllBytes(), StandardCharsets.UTF_8);
        } catch (IOException ioException) {
            throw new UncheckedIOException(ioException);
        }
    }

    ToolCallbackProvider toolCallbackProvider() {
        List<Object> tools = List.of(
            projectTools, projectWorkflowTools, componentTools, taskTools, taskDispatcherTools, scriptTools,
            clusterElementTools);

        List<ToolCallback> toolCallbacks = new ArrayList<>(List.of(ToolCallbacks.from(tools.toArray())));

        for (McpServerToolCallbackContributor contributor : mcpServerToolCallbackContributors) {
            toolCallbacks.addAll(contributor.getToolCallbacks());
        }

        return ToolCallbackProvider.from(toolCallbacks);
    }

    private McpAsyncServer createMcpAsyncServer(WebMvcStreamableServerTransportProvider transportProvider) {
        ToolCallbackProvider toolCallbackProvider = toolCallbackProvider();

        Set<String> registeredToolNames = Arrays.stream(toolCallbackProvider.getToolCallbacks())
            .map(toolCallback -> toolCallback.getToolDefinition()
                .name())
            .collect(Collectors.toSet());

        return McpServer.async(transportProvider)
            .serverInfo("mcp-server", "1.0.0")
            .instructions(buildInstructions(registeredToolNames))
            .capabilities(
                McpSchema.ServerCapabilities.builder()
                    .resources(false, true)
                    .tools(true)
                    .prompts(true)
                    .logging()
                    .build())
            .tools(McpToolUtils.toAsyncToolSpecifications(toolCallbackProvider.getToolCallbacks()))
            .build();
    }
}
