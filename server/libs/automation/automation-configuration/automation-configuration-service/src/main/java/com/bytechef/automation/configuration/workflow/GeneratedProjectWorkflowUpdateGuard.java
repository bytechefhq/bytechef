package com.bytechef.automation.configuration.workflow;

import com.bytechef.automation.configuration.domain.ProjectWorkflowType;
import com.bytechef.automation.configuration.service.ProjectWorkflowService;
import com.bytechef.platform.configuration.workflow.WorkflowUpdateGuard;
import org.springframework.stereotype.Component;

/**
 * @author Ivica Cardic
 */
@Component
public final class GeneratedProjectWorkflowUpdateGuard implements WorkflowUpdateGuard {

    private final ProjectWorkflowService projectWorkflowService;

    GeneratedProjectWorkflowUpdateGuard(ProjectWorkflowService projectWorkflowService) {
        this.projectWorkflowService = projectWorkflowService;
    }

    @Override
    public void checkUpdatable(String workflowId) {
        projectWorkflowService.fetchWorkflowProjectWorkflow(workflowId)
            .filter(projectWorkflow -> projectWorkflow.getType()
                .isGenerated())
            .ifPresent(projectWorkflow -> {
                throw new IllegalArgumentException(generatedWorkflowMessage(workflowId, projectWorkflow.getType()));
            });
    }

    public static String generatedWorkflowMessage(String workflowId, ProjectWorkflowType type) {
        return switch (type) {
            case AI_AGENT -> "Workflow %s is generated by an AI agent; edit it through the agent"
                .formatted(workflowId);
            case DATA_SYNC -> "Workflow %s is generated by a Data Sync; edit it through the Data Sync"
                .formatted(workflowId);
            case WORKFLOW -> throw new IllegalArgumentException("Workflow %s is not generated".formatted(workflowId));
        };
    }
}
