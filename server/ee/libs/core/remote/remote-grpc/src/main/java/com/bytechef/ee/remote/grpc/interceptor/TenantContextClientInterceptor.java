package com.bytechef.ee.remote.grpc.interceptor;

import com.bytechef.tenant.TenantContext;
import io.grpc.CallOptions;
import io.grpc.Channel;
import io.grpc.ClientCall;
import io.grpc.ClientInterceptor;
import io.grpc.ForwardingClientCall;
import io.grpc.Metadata;
import io.grpc.MethodDescriptor;

/**
 * Sends the caller's current tenant with every outgoing call.
 *
 * @version ee
 */
public class TenantContextClientInterceptor implements ClientInterceptor {

    @Override
    public <ReqT, RespT> ClientCall<ReqT, RespT> interceptCall(
        MethodDescriptor<ReqT, RespT> methodDescriptor, CallOptions callOptions, Channel channel) {

        String tenantId = TenantContext.getCurrentTenantId();

        return new ForwardingClientCall.SimpleForwardingClientCall<>(channel.newCall(methodDescriptor, callOptions)) {

            @Override
            public void start(Listener<RespT> responseListener, Metadata metadata) {
                metadata.put(GrpcMetadataKeys.TENANT_ID, tenantId);

                super.start(responseListener, metadata);
            }
        };
    }
}
