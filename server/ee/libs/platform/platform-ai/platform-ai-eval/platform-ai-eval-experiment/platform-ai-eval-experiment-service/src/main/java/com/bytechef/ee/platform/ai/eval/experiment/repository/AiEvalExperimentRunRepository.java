package com.bytechef.ee.platform.ai.eval.experiment.repository;

import com.bytechef.ee.platform.ai.eval.experiment.domain.AiEvalExperimentRun;
import java.util.List;
import java.util.Optional;
import org.springframework.data.repository.ListCrudRepository;

/**
 * @author Ivica Cardic
 * @version ee
 */
public interface AiEvalExperimentRunRepository extends ListCrudRepository<AiEvalExperimentRun, Long> {

    /**
     * Returns runs ordered by id ascending so callers (the executor's positional alignment loop, the GraphQL comparison
     * view, the public REST list endpoint) see a stable order. Without an explicit ORDER BY, PostgreSQL is free to
     * return rows in physical heap order, which can shuffle on autovacuum / page rewrites.
     */
    List<AiEvalExperimentRun> findAllByExperimentIdOrderByIdAsc(Long experimentId);

    long countByExperimentId(Long experimentId);

    long countByExperimentIdAndStatus(Long experimentId, int status);

    /**
     * Reverse lookup from a trace id to its source experiment run, if any. Used by the operator-console Traces tab to
     * surface a "View source experiment" cross-link when the trace was generated by an experiment replay rather than a
     * production API call. Returns at most one row because the executor stamps a unique trace id per replay.
     */
    Optional<AiEvalExperimentRun> findByTraceId(Long traceId);
}
